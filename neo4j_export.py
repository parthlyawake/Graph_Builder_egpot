"""
neo4j_export.py  —  GRAFT-CKG Neo4j Cypher Exporter
=====================================================
Paper Section V-D: Persistence layer for Batch 2 cross-team queries.

Exports the unified CKG workspace graph as Cypher UNWIND batch statements
compatible with Neo4j Community Edition (no driver dependency required).
Output is a .cypher file executable via cypher-shell or Neo4j Browser.

Usage:
    from neo4j_export import CypherExporter
    from multi_repo import WorkspaceCKGBuilder

    wb = WorkspaceCKGBuilder("workspace.yaml")
    wb.build()
    exporter = CypherExporter(wb.graph)
    exporter.export("output.cypher")

Or from CLI:
    python neo4j_export.py repos/online-boutique/workspace.yaml output.cypher
"""

from __future__ import annotations

import json
import os
import sys
from typing import Any, Dict

import networkx as nx

# Node type -> Neo4j label mapping
NODE_TYPE_LABELS = {
    "file": "File",
    "module": "Module",
    "class": "Class",
    "function": "Function",
    "variable": "Variable",
    "parameter": "Parameter",
    "service_contract": "ServiceContract",
    "rpc_contract": "RpcContract",
    "commit": "Commit",
    "external": "External",
    "unknown": "Symbol",
}

# Relations to export as Cypher relationship types
RELATION_LABELS = {
    "CONTAINS", "IMPORTS", "EXTENDS", "CALLS", "POLYMORPHIC_CALL",
    "PASSES_ARG", "DEFINES", "USES", "MUTATES", "RETURNS", "FLOWS_TO",
    "HTTP_CALLS", "IMPLEMENTS", "CONSUMES", "SEMANTIC_SIMILAR",
    "TOUCHES",
}

# Properties to export per node (whitelist for safety)
NODE_PROPS = {"name", "type", "file", "line", "docstring", "layer", "repo_id",
              "d_scope", "f_call", "c_type", "sha", "message", "author", "date"}

# Properties to export per edge
EDGE_PROPS = {"relation", "layer", "d_scope", "f_call", "c_type", "id_ctx",
              "lines_added", "lines_removed", "net_delta"}


def _safe_str(v: Any) -> str:
    """Escape a value for use in a Cypher string literal."""
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("\\", "\\\\").replace("'", "\\'")[:500] + "'"


def _node_id_to_neo4j(node_id: str) -> str:
    """Sanitize a node ID for use as a Neo4j property value."""
    return node_id.replace("\\", "/")


class CypherExporter:
    """
    Converts a NetworkX MultiDiGraph (GRAFT-CKG output) into
    Neo4j Cypher UNWIND batch statements.
    """

    def __init__(self, graph: nx.MultiDiGraph, batch_size: int = 500):
        self.graph = graph
        self.batch_size = batch_size

    def export(self, output_path: str) -> int:
        """
        Write Cypher to output_path.
        Returns the total number of statements written.
        """
        nodes = list(self.graph.nodes(data=True))
        edges = list(self.graph.edges(data=True))

        statements = 0
        with open(output_path, "w", encoding="utf-8") as f:
            f.write("// GRAFT-CKG Neo4j Export\n")
            f.write("// Generated by neo4j_export.py\n")
            f.write("// Run with: cypher-shell -u neo4j -p password < output.cypher\n\n")

            # Constraints (idempotent)
            f.write("// Uniqueness constraints\n")
            for label in set(NODE_TYPE_LABELS.values()):
                f.write(f"CREATE CONSTRAINT IF NOT EXISTS FOR (n:{label}) REQUIRE n.node_id IS UNIQUE;\n")
            f.write("\n")

            # Nodes in batches
            f.write("// === NODES ===\n")
            for i in range(0, len(nodes), self.batch_size):
                batch = nodes[i : i + self.batch_size]
                rows = []
                for nid, data in batch:
                    row = {"node_id": _node_id_to_neo4j(nid)}
                    ntype = data.get("type", "unknown")
                    row["neo4j_label"] = NODE_TYPE_LABELS.get(ntype, "Symbol")
                    for prop in NODE_PROPS:
                        val = data.get(prop)
                        if val is not None and val != "":
                            if isinstance(val, (dict, list)):
                                row[prop] = json.dumps(val)[:200]
                            else:
                                row[prop] = str(val)[:500]
                    rows.append(row)

                # Write UNWIND batch, grouped by label
                by_label: Dict[str, list] = {}
                for row in rows:
                    lbl = row.pop("neo4j_label")
                    by_label.setdefault(lbl, []).append(row)

                for label, label_rows in by_label.items():
                    rows_json = json.dumps(label_rows, ensure_ascii=False)
                    f.write(f"UNWIND {rows_json} AS row\n")
                    f.write(f"MERGE (n:{label} {{node_id: row.node_id}})\n")
                    f.write("SET n += row;\n\n")
                    statements += 1

            # Edges in batches
            f.write("// === RELATIONSHIPS ===\n")
            for i in range(0, len(edges), self.batch_size):
                batch = edges[i : i + self.batch_size]
                # Group by relation type
                by_rel: Dict[str, list] = {}
                for u, v, data in batch:
                    rel = data.get("relation", "RELATED_TO")
                    if rel not in RELATION_LABELS:
                        continue
                    row = {
                        "from": _node_id_to_neo4j(u),
                        "to": _node_id_to_neo4j(v),
                    }
                    for prop in EDGE_PROPS - {"relation"}:
                        val = data.get(prop)
                        if val is not None and val != "":
                            row[prop] = val if isinstance(val, (int, float, bool)) else str(val)[:200]
                    by_rel.setdefault(rel, []).append(row)

                for rel, rel_rows in by_rel.items():
                    rows_json = json.dumps(rel_rows, ensure_ascii=False)
                    f.write(f"UNWIND {rows_json} AS row\n")
                    f.write("MATCH (a {node_id: row.from}), (b {node_id: row.to})\n")
                    f.write(f"MERGE (a)-[r:{rel}]->(b)\n")
                    # Set numeric edge properties
                    prop_sets = [p for p in EDGE_PROPS - {"relation"} if p in (rel_rows[0] if rel_rows else {})]
                    if prop_sets:
                        sets = ", ".join(f"r.{p} = row.{p}" for p in prop_sets)
                        f.write(f"SET {sets};\n\n")
                    else:
                        f.write(";\n\n")
                    statements += 1

        print(f"[*] Neo4j export: {len(nodes)} nodes, {len(edges)} edges -> {statements} Cypher statements")
        print(f"[*] Written to: {output_path}")
        return statements

    def to_string(self) -> str:
        """Return the Cypher script as a string (for small graphs)."""
        import tempfile
        with tempfile.NamedTemporaryFile(suffix=".cypher", delete=False, mode="w") as f:
            tmp = f.name
        self.export(tmp)
        with open(tmp, "r", encoding="utf-8") as f:
            content = f.read()
        os.unlink(tmp)
        return content


def _cli():
    import argparse
    parser = argparse.ArgumentParser(
        description="Export GRAFT-CKG graph to Neo4j Cypher statements"
    )
    parser.add_argument("source", help="Workspace YAML/JSON or single repo path")
    parser.add_argument("output", nargs="?", default="graft_ckg_export.cypher",
                        help="Output .cypher file (default: graft_ckg_export.cypher)")
    parser.add_argument("--batch-size", type=int, default=500,
                        help="UNWIND batch size (default 500)")
    args = parser.parse_args()

    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

    if args.source.endswith((".yaml", ".yml", ".json")):
        from multi_repo import WorkspaceCKGBuilder
        wb = WorkspaceCKGBuilder(args.source)
        wb.build()
        graph = wb.graph
    else:
        from graft_ckg import CKGBuilder
        b = CKGBuilder(args.source)
        b.build()
        graph = b.graph

    exporter = CypherExporter(graph, batch_size=args.batch_size)
    exporter.export(args.output)


if __name__ == "__main__":
    _cli()
